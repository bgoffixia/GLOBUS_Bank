export function isAppLanguage(value: unknown): value is AppLanguage {
  return typeof value === 'string' && languageCodes.has(value);
}

export function readSavedLanguage(storage?: Pick<Storage, 'getItem'>): AppLanguage {
  try {
    const source = storage ?? (typeof window !== 'undefined' ? window.localStorage : undefined);
    const stored = source?.getItem(APP_LANGUAGE_STORAGE_KEY);
    return isAppLanguage(stored) ? stored : 'en';
  } catch {
    return 'en';
  }
}

export function translateText(
  language: AppLanguage,
  message: string,
  values: TranslationValues = {},
): string {
  const translated = language === 'en' ? message : translations[language]?.[message] ?? message;
  return translated.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}

const LanguageContext = createContext<TranslationContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<AppLanguage>(() => readSavedLanguage());
  const setLanguage = useCallback((next: AppLanguage) => {
    if (!isAppLanguage(next)) return;
    updateLanguage(next);
    try {
      window.localStorage.setItem(APP_LANGUAGE_STORAGE_KEY, next);
    } catch {
      // Keep the active selection for this session if storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = appLanguages.find(item => item.code === language)?.locale ?? 'en-NG';
  }, [language]);

  useEffect(() => {
    const syncLanguage = (event: StorageEvent) => {
      if (event.key === APP_LANGUAGE_STORAGE_KEY && isAppLanguage(event.newValue)) {
        updateLanguage(event.newValue);
      }
    };
    window.addEventListener('storage', syncLanguage);
    return () => window.removeEventListener('storage', syncLanguage);
  }, []);

  const value = useMemo<TranslationContextValue>(() => {
    const locale = appLanguages.find(item => item.code === language)?.locale ?? 'en-NG';
    return {
      language,
      locale,
      setLanguage,
      t: (message, values) => translateText(language, message, values),
    };
  }, [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider.');
  return context;
}
